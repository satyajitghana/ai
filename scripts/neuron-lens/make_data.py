"""Turn the lens_check.py outputs into components/articles/neuron-lens/data.ts (no number is typed by hand).

usage: NLENS_OUT=<dir with results.json and reads.jsonl> python3 -I make_data.py
"""
import json, os, math

OUT = os.environ["NLENS_OUT"]
DEST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "components", "articles", "neuron-lens", "data.ts")

res = json.load(open(os.path.join(OUT, "results.json")))
recs = [json.loads(l) for l in open(os.path.join(OUT, "reads.jsonl"))]

CAMEL = {
    "r_logit": "rLogit", "r_J": "rJ", "r_J_mismatched": "rCtrl", "steer_rel": "rel", "rho_logit": "rhoLogit", "rho_J": "rhoJ",
    "x4_r_logit": "rLogit4", "x4_r_J": "rJ4", "x4_rel": "rel4", "x16_r_logit": "rLogit16", "x16_r_J": "rJ16", "x16_rel": "rel16",
    "J_halves_top1": "halvesTop1", "J_halves_top10": "halvesTop10", "logit_vs_J_top10": "logitVsJTop10",
    "naive_hit10": "naive10", "K_hit10": "k10", "Jread_hit10": "j10", "ctrl_naive_hit10": "ctrlNaive10", "ctrl_K_hit10": "ctrlK10",
    "naive_hit50": "naive50", "K_hit50": "k50", "Jread_hit50": "j50", "ctrl_naive_hit50": "ctrlNaive50", "ctrl_K_hit50": "ctrlK50",
}


def row(r):
    o = {"name": r["name"], "neurons": r["neurons"], "poles": r["poles"]}
    if "layer" in r:
        o["layer"] = r["layer"]
    for k, v in CAMEL.items():
        x = r.get(k)
        o[v] = None if x is None or (isinstance(x, float) and math.isnan(x)) else round(float(x), 3)
    return o


def ts(v):
    return json.dumps(v, ensure_ascii=False, indent=1)


# the authors' own Qwen3-8B table (findings section 3): median Pearson r between a lens read of a pole's write and the measured
# change in log-probabilities, 36 layers
AUTHORS_STEER = [
    {"layer": 0, "logit": 0.09, "J": 0.38, "R": 0.35, "control": 0.01},
    {"layer": 4, "logit": 0.09, "J": 0.38, "R": 0.46, "control": -0.01},
    {"layer": 8, "logit": 0.12, "J": 0.42, "R": 0.51, "control": 0.01},
    {"layer": 12, "logit": 0.25, "J": 0.58, "R": 0.64, "control": -0.02},
    {"layer": 16, "logit": 0.36, "J": 0.65, "R": 0.74, "control": 0.0},
    {"layer": 20, "logit": 0.59, "J": 0.81, "R": 0.87, "control": 0.01},
    {"layer": 24, "logit": 0.83, "J": 0.92, "R": 0.94, "control": 0.0},
    {"layer": 28, "logit": 0.90, "J": 0.96, "R": 0.98, "control": -0.01},
    {"layer": 32, "logit": 0.94, "J": 0.99, "R": 0.99, "control": -0.01},
]

# case studies: chosen by a fixed rule (see the article), one + pole per sampled depth, the neuron with the most firing tokens
# found in the top 50 of its K-style and J-style input reads. These are the best cases at each depth, not typical ones.
cases = []
for L in sorted({r["L"] for r in recs}):
    rs = [r for r in recs if r["L"] == L and r.get("p_fire_tokens")]
    if not rs:
        continue
    best = max(rs, key=lambda r: (r.get("p_K_hit50") or 0) + (r.get("p_Jread_hit50") or 0))
    cases.append({
        "layer": L, "neuron": best["n"],
        "writeLogit": best["top_write_logit"][:6], "writeJ": best["top_write_J"][:6],
        "steered": (best.get("p_delta_top") or [])[:6],
        "readK": (best.get("p_K_top") or [])[:6], "readEmbed": (best.get("p_naive_top") or [])[:6], "readJ": (best.get("p_Jread_top") or [])[:6],
        "fires": (best.get("p_fire_tokens") or [])[:6],
        "rLogit": None if best.get("p_r_logit") is None else round(best["p_r_logit"], 2),
        "rJ": None if best.get("p_r_J") is None else round(best["p_r_J"], 2),
        "rel": None if best.get("p_steer_rel") is None else round(best["p_steer_rel"], 3),
    })

run = {
    "model": "Qwen3-0.6B", "layersTotal": 28, "sampledNeurons": res["n_neurons"], "perLayer": res["per_layer_neurons"],
    "sampledLayers": res["layers"], "keptVocab": res["kept_vocab"],
}

src = f"""// Generated by scripts/neuron-lens/make_data.py from the run's results.json and reads.jsonl. Do not hand-edit numbers.
// Measured on a shared 4-core cloud VM, CPU only, Qwen/Qwen3-0.6B (bf16 checkpoint, computed in float32).
export const RUN = {ts(run)} as const

export type Row = {{
  name: string
  layer?: number
  neurons: number
  poles: number
  rLogit: number | null
  rJ: number | null
  rCtrl: number | null
  rel: number | null
  rhoLogit: number | null
  rhoJ: number | null
  rLogit4: number | null
  rJ4: number | null
  rel4: number | null
  rLogit16: number | null
  rJ16: number | null
  rel16: number | null
  halvesTop1: number | null
  halvesTop10: number | null
  logitVsJTop10: number | null
  naive10: number | null
  k10: number | null
  j10: number | null
  ctrlNaive10: number | null
  ctrlK10: number | null
  naive50: number | null
  k50: number | null
  j50: number | null
  ctrlNaive50: number | null
  ctrlK50: number | null
}}

export const PER_LAYER: Row[] = {ts([row(r) for r in res["per_layer"]])}

export const BUCKETS: Row[] = {ts([row(r) for r in res["buckets"]])}

// The authors' Qwen3-8B numbers (neuron-lens findings, section 3): median Pearson r between a lens read of a pole's write and
// the measured change in next-token log-probabilities. 36 layers. Reported, not re-run.
export const AUTHORS_STEER = {ts(AUTHORS_STEER)} as const

export type Case = {{
  layer: number
  neuron: number
  writeLogit: string[]
  writeJ: string[]
  steered: string[]
  readK: string[]
  readEmbed: string[]
  readJ: string[]
  fires: string[]
  rLogit: number | null
  rJ: number | null
  rel: number | null
}}

export const CASES: Case[] = {ts(cases)}
"""
open(DEST, "w").write(src)
print("wrote", DEST, len(src), "bytes;", len(cases), "cases")
