#!/usr/bin/env bash
# Rebuild the SIMD kernels and regenerate the base64 module the engine embeds.
# Needs clang >= 15 with the wasm32 target and wasm-ld (apt: clang lld).
set -euo pipefail
cd "$(dirname "$0")"
OUT=../../components/neuron-lab/engine/kernels-wasm.ts
clang --target=wasm32 -O3 -msimd128 -nostdlib -ffreestanding -fno-builtin \
  -Wl,--no-entry -Wl,--import-memory -Wl,--initial-memory=1048576 -Wl,--max-memory=4294967296 -Wl,--export-dynamic -Wl,--allow-undefined -Wl,-z,stack-size=65536 \
  -o /tmp/kernels.wasm kernels.c
{
  echo "// GENERATED by scripts/neuron-lab/build-kernels.sh from kernels.c. Do not edit."
  echo "export const KERNELS_WASM_BASE64 = \"$(base64 -w0 /tmp/kernels.wasm)\""
} > "$OUT"
echo "wrote $OUT ($(stat -c %s /tmp/kernels.wasm) bytes of wasm)"
