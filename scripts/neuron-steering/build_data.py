"""Turns the JSON files written by extra.py (stages A-E) into components/articles/neuron-steering/data-extra.ts.

    python build_data.py --out DIR --ts ../../components/articles/neuron-steering/data-extra.ts
"""
import argparse, json, os, re
import numpy as np
from transformers import AutoTokenizer

ap = argparse.ArgumentParser()
ap.add_argument("--out", required=True)
ap.add_argument("--ts", required=True)
a = ap.parse_args()
J = lambda n: json.load(open(os.path.join(a.out, n)))
A, B, C, D, E = J("A.json"), J("B.json"), J("C.json"), J("D.json"), J("E.json")
tok = AutoTokenizer.from_pretrained("Qwen/Qwen3-0.6B")
# links whose lens is a list of vulgar words are left out of the figure
BLOCK = re.compile(r"porn|sex|erot|nude|libertin", re.I)
r1 = lambda x: round(float(x), 1)
r2 = lambda x: round(float(x), 2)
r3 = lambda x: round(float(x), 3)

out = ["// Generated by scripts/neuron-steering/build_data.py from the JSON files of extra.py. Do not hand-edit.",
       "// Qwen3-0.6B, float32, CPU. See the article's text for what each block is.", ""]


def emit(name, value, typ=None):
    out.append(f"export const {name}{': ' + typ if typ else ''} = {json.dumps(value, ensure_ascii=False, indent=1)}\n")


# --- sensitivity to the reference passage, and the sink token
a1 = A["A1"]
emit("SENS", {
    "passages": a1["passages"],
    "tokens": [a1["tokens"][p] for p in a1["passages"]],
    "medians": [[r1(x) for x in a1["median_norm"][p]] for p in a1["passages"]],
    "spread": [r2(x) for x in a1["spread_max_over_min"]],
    "sink": [r1(x) for x in a1["sink_over_median"]],
    "peak0": [r3(x) for x in A["A1b"]["share_of_neurons_peaking_at_token0"]],
})

# --- add / multiply / ablate
emit("MODES", [{"id": f"L{r['neuron'][0]}N{r['neuron'][1]}", "actFr": r2(r["mean_act_fr"]), "actEn": r2(r["mean_act_en"]),
                "add": [r3(r["add_0.2"]["kl_fr"]), r3(r["add_0.2"]["kl_en"])],
                "mul3": [r3(r["mul_3"]["kl_fr"]), r3(r["mul_3"]["kl_en"])],
                "mul0": [r3(r["mul_0"]["kl_fr"]), r3(r["mul_0"]["kl_en"])]} for r in A["A3"]],
     "{ id: string; actFr: number; actEn: number; add: [number, number]; mul3: [number, number]; mul0: [number, number] }[]")
emit("PER_TOKEN", {k: {"unit": r2(v["unit"]), "colNorm": r3(v["col_norm"]),
                       "fr": [{"t": t, "v": r2(x)} for t, x in zip(*v["fr"])],
                       "en": [{"t": t, "v": r2(x)} for t, x in zip(*v["en"])]} for k, v in D["D2"].items()},
     "Record<string, { unit: number; colNorm: number; fr: { t: string; v: number }[]; en: { t: string; v: number }[] }>")

# --- batching and precision
p = "Tell me about yourself."
trio = [p, p + " Answer in two sentences.", p.upper()]
lens = [len(tok(tok.apply_chat_template([{"role": "user", "content": t}], tokenize=False, add_generation_prompt=True, enable_thinking=False)).input_ids) for t in trio]
bs, bf = E["batch_vs_single"], E["bf16_vs_fp32"]
emit("TRIO", {"promptLens": lens, "same": sum(x["same"] for x in bs), "total": len(bs),
              "bf16Same": sum(x["same"] for x in bf), "bf16Total": len(bf),
              "bf16First": [x["first_divergence"] for x in bf], "batchFirst": [x["first_divergence"] for x in bs if not x["same"]]},
     "{ promptLens: number[]; same: number; total: number; bf16Same: number; bf16Total: number; bf16First: (number | null)[]; batchFirst: (number | null)[] }")

# --- logit lens examples
z = np.load(os.path.join(a.out, "lens_index.npz"))
up, down = z["up"], z["down"]
ids = [(16, 477), (17, 649), (20, 565), (23, 166)]
for pair in C["C3_search"]["pairs"]:
    for key in ("top1", "top2"):
        if pair[key]:
            _, l, n = pair[key][0]
            ids.append((int(l), int(n)))
seen, ex = set(), []
for l, n in ids:
    if (l, n) in seen:
        continue
    seen.add((l, n))
    ex.append({"id": f"L{l} N{n}", "up": [tok.decode([t]) for t in up[l, n]], "down": [tok.decode([t]) for t in down[l, n]]})
emit("LENS", {"layers": int(B["shape"][0]), "neurons": int(B["shape"][1]), "seconds": int(B["seconds"]), "mb": r1(B["bytes_npz"] / 1e6), "examples": ex})

# --- steer lens vs logit lens
emit("STEER", [{"layer": c["layer"], "medianKl": r2(c["median_kl"]), "overlapUp": r1(c["mean_overlap_up"]),
                "overlapDown": r1(c["mean_overlap_down"]), "n": c["n"]} for c in C["C1"]])

# --- connections
c2 = C["C2"]
emit("LINKS", {"sourceLayer": c2["source_layer"], "sources": c2["sources"], "k": c2["k"], "medianZ": r1(c2["median_top24_z"]),
               "sharePos": r2(c2["share_positive_sign"]), "byDistance": [r3(x) for x in c2["share_by_layer_distance"]],
               "named": {k: [x for x in v if not BLOCK.search(" ".join(x["lens"]))] for k, v in c2["named"].items()}},
     "{ sourceLayer: number; sources: number; k: number; medianZ: number; sharePos: number; byDistance: number[]; named: Record<string, { layer: number; n: number; z: number; sign: number; lens: string[] }[]> }")

# --- combinations
combo = []
runs = list(C["C3"]) + (J("F.json")["runs"] if os.path.exists(os.path.join(a.out, "F.json")) else [])
for r in runs:
    w1, w2 = r["words"]
    n = r["baseline"]["n"]
    cnt = lambda d: {"c1": d[w1], "c2": d[w2]}
    rec = {"words": [w1, w2], "dose": r["dose"], "n": n, "base": cnt(r["baseline"]),
           "single": [{"id": k, **cnt(v)} for k, v in r["single"].items()],
           "pair": [{"id": k.replace("+", " + "), **cnt(v)} for k, v in r["pair"].items()],
           "ctrlSingle": [cnt(v) for v in r["control_single"]], "ctrlPair": [cnt(v) for v in r["control_pair"]]}
    bs1 = max(s["c1"] for s in rec["single"]); bs2 = max(s["c2"] for s in rec["single"])
    bp1 = max(s["c1"] for s in rec["pair"]); bp2 = max(s["c2"] for s in rec["pair"])
    cp1 = max(s["c1"] for s in rec["ctrlPair"]); cp2 = max(s["c2"] for s in rec["ctrlPair"])
    rec["summary"] = (f"{w1}/{w2} out of {n}: no steering {rec['base']['c1']}/{rec['base']['c2']}; best single {bs1}/{bs2}; "
                      f"best pair {bp1}/{bp2}; random pairs (max) {cp1}/{cp2}.")
    combo.append(rec)
emit("COMBO", combo, "{ words: [string, string]; dose: number; n: number; base: { c1: number; c2: number }; single: { id: string; c1: number; c2: number }[]; pair: { id: string; c1: number; c2: number }[]; ctrlSingle: { c1: number; c2: number }[]; ctrlPair: { c1: number; c2: number }[]; summary: string }[]")

# --- write-direction geometry
emit("NN", [{"layer": d["layer"], "nn4": r3(d["nn4_cos"]), "random": r3(d["random_nn4_cos"]), "meanAbs": r3(d["mean_abs_cos"])} for d in D["D1"]])
emit("MODEL", {"params": D["params"], "search": C["C3_search"]})

with open(a.ts, "w") as f:
    f.write("\n".join(out))
print("wrote", a.ts)
