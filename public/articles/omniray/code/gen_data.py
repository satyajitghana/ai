"""Turn oracle_results.json and demo_metrics.json into components/articles/omniray/data.ts.

Usage: python3 -I gen_data.py oracle_results.json demo_metrics.json components/articles/omniray/data.ts
"""
import json, sys

oracle = json.load(open(sys.argv[1]))
demo = json.load(open(sys.argv[2]))

# Table 1 of the paper (reported): mean angular error in degrees. Columns: fisheye, equirectangular, catadioptric.
PAPER_T1 = {
    "pinhole": (5.731, 48.080, 50.434),
    "radial": (0.002, 22.802, 0.104),
    "sh": (0.276, 0.641, 0.295),
    "radialSh": (0.075, 0.217, 0.174),
}
PAPER_COL = {"fisheye": 0, "equirectangular": 1, "catadioptric": 2}
LABEL = {"fisheye": "fisheye 180°", "equirectangular": "2:1 panorama", "catadioptric": "mirror camera", "pinhole": "pinhole 90°"}

# Table 4 of the paper (reported): mean ray error in degrees per camera type (OmniRay, UniK3D, Depth Anything 3).
PAPER_T4 = {
    "pinhole": (0.155, 3.619, 6.604),
    "fisheye": (0.154, 7.055, 28.727),
    "panorama": (0.110, 8.336, 63.752),
    "gopro": (5.533, 6.342, 16.637),
    "catadioptric": (1.120, 75.702, 121.566),
}
DEMO_LABEL = {"pinhole": "pinhole (CO3Dv2)", "fisheye": "fisheye (PanoCity)", "panorama": "panorama (PanoCity)", "gopro": "GoPro (PanoCity)", "catadioptric": "catadioptric (PanoCity)"}
HELD = {"gopro", "catadioptric"}


def r(v, nd=4):
    return round(float(v), nd)


lines = ["// Generated by public/articles/omniray/code/gen_data.py from oracle_results.json and demo_metrics.json. Do not edit by hand.", ""]

lines.append("export type OracleRow = { pinhole: number; sh: number; radial: number; radialSh: number; free: number }")
lines.append("export type Geom = { id: string; label: string; n: number; oracle: OracleRow; paper?: Partial<OracleRow> }")
lines.append("export const GEOMS: Geom[] = [")
for gid in ("fisheye", "equirectangular", "catadioptric", "pinhole"):
    g = oracle["geometries"][gid]
    row = {"pinhole": g["pinhole(6)"]["mean_deg"], "sh": g["SH only (L=7)"]["mean_deg"], "radial": g["radial"]["mean_deg"],
           "radialSh": g["radial+SH"]["mean_deg"], "free": g["radial+SH+free"]["mean_deg"]}
    paper = ""
    if gid in PAPER_COL:
        c = PAPER_COL[gid]
        paper = ", paper: { " + ", ".join(f"{k}: {v[c]}" for k, v in PAPER_T1.items()) + " }"
    lines.append(f'  {{ id: "{gid}", label: "{LABEL[gid]}", n: {g["n_pixels"]}, oracle: {{ ' + ", ".join(f"{k}: {r(v, 5)}" for k, v in row.items()) + f" }}{paper} }},")
lines.append("]")
lines.append("")

lines.append("export type SweepRow = { amp: number; radial: number; radialSh: number; free: number; fracRadial: number; fracRadialSh: number; fracFree: number }")
for name, key in (("SMOOTH_SWEEP", "smooth_sweep"), ("LOCAL_SWEEP", "local_sweep")):
    lines.append(f"export const {name}: SweepRow[] = [")
    for amp, st in oracle[key].items():
        lines.append(
            f"  {{ amp: {float(amp):g}, radial: {r(st['radial']['mean_deg'], 5)}, radialSh: {r(st['radial+SH']['mean_deg'], 5)}, free: {r(st['radial+SH+free']['mean_deg'], 5)}, "
            f"fracRadial: {r(st['radial']['frac_over_thr'], 4)}, fracRadialSh: {r(st['radial+SH']['frac_over_thr'], 4)}, fracFree: {r(st['radial+SH+free']['frac_over_thr'], 4)} }},"
        )
    lines.append("]")
    lines.append("")

lines.append("export type DemoRow = { id: string; label: string; heldOut: boolean; omniray: number; unik3d: number; da3: number; paper: { omniray: number; unik3d: number; da3: number } }")
lines.append("export const DEMO: DemoRow[] = [")
for cid in ("pinhole", "fisheye", "panorama", "gopro", "catadioptric"):
    d = demo[cid]
    p = PAPER_T4[cid]
    lines.append(
        f'  {{ id: "{cid}", label: "{DEMO_LABEL[cid]}", heldOut: {"true" if cid in HELD else "false"}, omniray: {r(d["omniray"]["ray_mean_deg"], 4)}, unik3d: {r(d["unik3d"]["ray_mean_deg"], 4)}, da3: {r(d["da3"]["ray_mean_deg"], 4)}, '
        f"paper: {{ omniray: {p[0]}, unik3d: {p[1]}, da3: {p[2]} }} }},"
    )
lines.append("]")
open(sys.argv[3], "w").write("\n".join(lines) + "\n")
print("wrote", sys.argv[3])
