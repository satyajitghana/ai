"""Builds components/articles/codex-harness-from-the-source/data.ts from the research JSON files
(graph, counts, history) and our four toy outputs. Run: python3 -I gen_data.py <out.ts>."""
import json, sys, difflib
R = "/tmp/claude-0/-home-user-ai/2b081fe6-e329-54d0-85fc-c1b074e1ebe7/scratchpad/codex/"
C = json.load(open(R + "data-c.json"))
toy1 = json.load(open("toy1_apply_patch.json")); toy2 = json.load(open("toy2_scheduler.json"))
toy3 = json.load(open("toy3_compaction.json")); toy4 = json.load(open("toy4_execpolicy.json"))
proto = json.load(open("protocol_recount.json"))
LAYER_ORDER = ["protocol & schema", "services & I/O", "execution & sandbox", "core engine", "extensibility", "hosts & front ends"]
nodes = C["graph"]["nodes"]
idx = {n["id"]: i for i, n in enumerate(nodes)}
node_rows = [[n["id"].replace("codex-", ""), LAYER_ORDER.index(n["layer"]), n["rust_lines"], n["tests"], n["fan_in"], n["fan_out"]] for n in nodes]
edge_rows = [[idx[e["from"]], idx[e["to"]]] for e in C["graph"]["edges"]]
layers = [{"id": k, "crates": C["layers"][k]["crates"], "lines": C["layers"][k]["rust_lines"], "tests": C["layers"][k]["tests"]} for k in LAYER_ORDER]
catalog = [{"slug": r["slug"], "window": r["resolved"], "auto": r["auto_compact_limit"], "full": r["full_limit"], "lite": bool(r["use_responses_lite"]),
            "toolMode": r["tool_mode"], "words": r["template_words"]} for r in toy3]
cases = [{"name": r["case"], "passes": r["passes_used"], "result": r["result"], "error": r["error"], "precheck": r["verified_precheck"]} for r in toy1]
examples = []
for r in toy1:
    e = r.get("example")
    if e:
        diff = "".join(difflib.unified_diff(e["before"].splitlines(True), e["after"].splitlines(True), "before", "after", n=1))
        examples.append({"name": r["case"], "file": e["file"], "diff": diff, "patch": e["patch"]})
fam = proto["families"]
out = {
 "LAYERS": layers, "NODES": node_rows, "EDGES": edge_rows,
 "TOP_FAN_IN": C["graph"]["top_fan_in"], "TOP_FAN_OUT": C["graph"]["top_fan_out"],
 "CATALOG": catalog, "PATCH_CASES": cases, "PATCH_EXAMPLES": examples,
 "SCHED": toy2, "EXEC_RULES": toy4["rules"],
 "EXEC_RESULTS": [{"command": r["command"], "split": r["split_into_segments"], "effective": r["effective"], "bypass": r["bypass_sandbox"],
                   "segments": [{"argv": s["argv"], "decision": s["decision"], "why": s["why"]} for s in r["segments"]]} for r in toy4["results"]],
 "PROTO_CLIENT_METHODS": proto["client_requests"], "PROTO_NOTIF_METHODS": proto["server_notifications"],
 "PROTO_SERVER": proto["server_requests"] + ["applyPatchApproval (legacy)", "execCommandApproval (legacy)"],
 "PROTO_CLIENT": fam, "PROTO_NOTIF": [["thread", 32], ["item", 14], ["turn", 5], ["mcpServer", 3], ["account", 3], ["model", 3], ["hook", 2], ["process", 2], ["externalAgentConfig", 2], ["modelProvider", 2], ["fuzzyFileSearch", 2], ["error", 1], ["skills", 1], ["project", 1]],
 "PER_DAY": C["history"]["per_day"], "MONTHS": [["May", 352], ["Jun", 929], ["Jul", 879], ["Aug", 1266], ["Sep", 1617], ["Oct", 1257]],
 "AREAS": C["history"]["area_commits"][:14], "EXTENSIONS": sorted(C["extensions"].items(), key=lambda kv: -kv[1]),
 "LANG": sorted([[k, v["lines"]] for k, v in C["loc"]["lines_by_language"].items()], key=lambda kv: -kv[1]),
}
body = "// Generated by gen_data.py (kept in public/articles/codex-harness-from-the-source/toys/) from the research JSON and the four toy outputs.\n// Do not hand-edit numbers. Repo facts are read from openai/codex at 67f0994b (2026-10-31).\n"
for k, v in out.items():
    body += f"export const {k} = {json.dumps(v, ensure_ascii=False, separators=(',', ':'))} as const\n"
open(sys.argv[1], "w").write(body)
print(sys.argv[1], len(body), "bytes;", {k: (len(v) if hasattr(v, '__len__') else v) for k, v in out.items()})
