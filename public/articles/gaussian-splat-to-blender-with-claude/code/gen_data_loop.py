import json
import os

here = os.path.dirname(os.path.abspath(__file__))
cells = [json.load(open(os.path.join(here, "loop_%d.json" % i))) for i in range(6)]
rows = [
    dict(
        init=c["init"],
        cameras=c["cameras"],
        reached=c["reached"],
        seeds=c["seeds"],
        evalsMedian=c["evals_median"],
        sil=round(c["sil_iou_median"], 3),
        iou3d=round(c["iou3d_median"], 3),
        iou3dStart=round(c["iou3d_start_median"], 3),
    )
    for c in cells
]
