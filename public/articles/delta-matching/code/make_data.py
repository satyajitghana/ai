"""Turns the measured JSON (toy_rowsum.json, worked_row.json, runs/*.json) into components/articles/delta-matching/data.ts."""
import glob, json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
runs_dir = sys.argv[2] if len(sys.argv) > 2 else None
rs = json.load(open(os.path.join(here, "toy_rowsum.json")))
wr = json.load(open(os.path.join(here, "worked_row.json")))
g = lambda x: float("%.4g" % x)
rows = []
for r in rs["rows"]:
    rows.append({"inputs": r["inputs"], "logitStd": r["logit_std"],
                 **{m: {"pre": g(r["methods"][m]["pre"][0]), "post": g(r["methods"][m]["post"][0]), "dk": g(r["methods"][m]["dk_colsum"][0])} for m in ("stale", "consistent", "matched")},
                 "relErr": {k: g(v[0]) for k, v in r["fp8_rel_error_vs_exact"].items()}})
d = {"rowsum": rows, "worked": {
    "keys": wr["keys"], "P": [g(x) for x in wr["P"]], "Ph": [g(x) for x in wr["P_hat"]], "dPh": [g(x) for x in wr["dP_hat"]],
    "delta": {k: g(v) for k, v in wr["delta"].items()}, "dS": {k: [g(x) for x in v] for k, v in wr["dS"].items()},
    "rowSum": {k: float("%.3g" % v) for k, v in wr["row_sum"].items()}, "absSum": {k: g(v) for k, v in wr["abs_sum"].items()},
    "eq2": {k: float("%.3g" % v) for k, v in wr["eq2_terms"].items()}}}
if runs_dir:
    agg = {}
    for f in sorted(glob.glob(os.path.join(runs_dir, "*.json"))):
        r = json.load(open(f)); agg.setdefault(r["mode"], []).append(r)
    train = {}
    for mode, rs_ in agg.items():
        steps = [c[0] for c in rs_[0]["curve"]]
        n = min(len(r["curve"]) for r in rs_)
        loss = [g(sum(r["curve"][i][1] for r in rs_) / len(rs_)) for i in range(n)]
        gp = [[g(sum(r["gains"][i][1][l]["max_gain_prod"] for r in rs_) / len(rs_)) for i in range(min(len(r["gains"]) for r in rs_))] for l in range(2)]
        ts = [[g(sum(r["gains"][i][1][l]["top_channel_share"] for r in rs_) / len(rs_)) for i in range(min(len(r["gains"]) for r in rs_))] for l in range(2)]
        res = [[g(sum(r["resid"][i][1] for r in rs_) / len(rs_)), g(sum(r["resid"][i][2] for r in rs_) / len(rs_))] for i in range(min(len(r["resid"]) for r in rs_))] if mode != "ref" else []
        train[mode] = {"seeds": len(rs_), "steps": steps[:n], "loss": loss, "val": [g(r["val_ce"]) for r in rs_],
                       "gainStep": [x[0] for x in rs_[0]["gains"]], "maxGainProd": gp, "topShare": ts, "resid": res}
    d["train"] = train
hdr = "// Generated by public/articles/delta-matching/code/make_data.py from the measured JSON files next to it. Do not edit by hand.\n"
open(out, "w").write(hdr + "export const DATA = " + json.dumps(d, indent=1) + " as const\n")
print("wrote", out, len(json.dumps(d)))
